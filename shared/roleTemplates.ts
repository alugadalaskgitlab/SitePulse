const CREATE_EDIT = p({ view: true, create: true, edit: true, view_reports: true, export: true });
const CREATE_ONLY = p({ view: true, create: true });

type SectionOverrides = Partial<Record<SectionKey, P>>;

function buildMatrix(base: P, overrides: SectionOverrides): PermissionMatrix {
  const m = emptyMatrix();
  for (const k of SECTION_KEYS) {
    m[k] = overrides[k] ? p(overrides[k]!) : { ...base };
  }
  return m;
}

