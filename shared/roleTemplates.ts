type P = {
  view?: boolean; create?: boolean; edit?: boolean; delete?: boolean;
  view_reports?: boolean; export?: boolean; approve?: boolean; notify?: boolean;
};

function p(vals: P) {
  return {
    view: false, create: false, edit: false, delete: false,
    view_reports: false, export: false, approve: false, notify: false,
    ...vals,
  };
}

