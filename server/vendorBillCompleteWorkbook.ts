import * as xlsx from "xlsx";

const cellValue = (value: any) => {
  if (value == null) return "Not recorded";
  if (typeof value === "object") return JSON.stringify(value);
  return value;
};

const headerRows = (header: any) => [
  ["Generated at", header.generatedAt],
  ["Generated by", header.generatedBy],
  ["Bill count", header.billCount],
  ["Filters in force", JSON.stringify(header.filters)],
  ["Site scope", header.siteScope],
  [],
];

function appendSheet(
  workbook: xlsx.WorkBook,
  name: string,
  header: any,
  columns: string[],
  rows: any[][],
) {
  const sheet = xlsx.utils.aoa_to_sheet([
    ...headerRows(header),
    columns,
    ...rows,
  ]);
  sheet["!cols"] = columns.map(column => ({ wch: Math.max(14, Math.min(column.length + 4, 42)) }));
  const tableRow = headerRows(header).length;
  if (rows.length) {
    sheet["!autofilter"] = {
      ref: xlsx.utils.encode_range(
        { r: tableRow, c: 0 },
        { r: tableRow + rows.length, c: columns.length - 1 },
      ),
    };
  }
  xlsx.utils.book_append_sheet(workbook, sheet, name);
}

/** Render one already-assembled export. No bill selection or financial math here. */
export function buildVendorBillCompleteWorkbook(assembly: any) {
  const workbook = xlsx.utils.book_new();
  const billColumns = [
    "Bill ID", "Bill Number", "Bill Date", "Period From", "Period To", "Bill Type", "Category", "Site", "Site ID", "Supplied To",
    "Recorded Vendor Name", "Vendor Master ID", "Vendor Master Name", "Vendor Link Status",
    "Current Status", "Draft By", "Draft At", "Verified By", "Verified At", "Approved By", "Approved At", "Paid By", "Paid At",
    "Voided", "Void Reason", "Voided By", "Voided At",
     "Gross", "Payables Basis Gross", "Breakdown Deduction", "Breakdown Reason(s)", "HSD Recovery", "HSD Reason(s)",
    "Other Debit", "Other Debit Reason(s)", "Advance Adjustment", "Advance Reason(s)",
    "Other Credit", "Other Credit Reason(s)", "Net", "TDS As Recorded", "Amount Paid", "Balance",
    "Net Source", "TDS Evidence Incomplete", "Adjustment Details (JSON)", "Hire Statements (JSON)",
    "Created By", "Created At", "Frozen Calculation Snapshot Exists",
  ];
  const billRows = assembly.bills.map((bill: any) => {
    const byCategory = (category: string) => {
      const rows = bill.money.adjustmentDetails?.[category] || [];
      return rows.length
        ? {
            amount: rows.reduce((sum: number, row: any) => sum + Number(row.amount || 0), 0),
            reasons: rows.map((row: any) => `${row.reason} [${row.source}; stored=${cellValue(row.storedAmount)}]`).join("\n"),
          }
        : { amount: "Not recorded", reasons: "Not recorded" };
    };
    const b = byCategory("breakdownDeduction");
    const h = byCategory("hsdRecovery");
    const od = byCategory("otherDebit");
    const a = byCategory("advanceAdjustment");
    const c = byCategory("otherCredit");
    return [
      cellValue(bill.identity.billId), cellValue(bill.identity.billNumber), cellValue(bill.identity.billDate),
      cellValue(bill.identity.periodFrom), cellValue(bill.identity.periodTo), cellValue(bill.identity.billType),
      cellValue(bill.identity.category), cellValue(bill.identity.site), cellValue(bill.identity.siteId),
      cellValue(bill.identity.suppliedTo), cellValue(bill.vendor.recordedName),
      cellValue(bill.vendor.linkedVendorMasterId), cellValue(bill.vendor.linkedVendorMasterName),
      cellValue(bill.vendor.linkStatus), cellValue(bill.status.current),
      cellValue(bill.status.draft.who), cellValue(bill.status.draft.when),
      cellValue(bill.status.verified.who), cellValue(bill.status.verified.when),
      cellValue(bill.status.approved.who), cellValue(bill.status.approved.when),
      cellValue(bill.status.paid.who), cellValue(bill.status.paid.when),
      bill.status.voided, cellValue(bill.status.voidReason), cellValue(bill.status.voidedBy), cellValue(bill.status.voidedAt),
       cellValue(bill.money.gross), cellValue(bill.money.payablesBasisGross), b.amount, b.reasons, h.amount, h.reasons, od.amount, od.reasons,
      a.amount, a.reasons, c.amount, c.reasons, cellValue(bill.money.net), cellValue(bill.money.tds),
      cellValue(bill.money.amountPaid), cellValue(bill.money.balance), cellValue(bill.money.netSource),
      bill.money.tdsEvidenceIncomplete, JSON.stringify(bill.money.adjustmentDetails),
      JSON.stringify(bill.hireStatements), cellValue(bill.provenance.createdBy),
      cellValue(bill.provenance.createdAt), bill.provenance.hasFrozenCalculationSnapshot,
    ];
  });
  appendSheet(workbook, "Vendor Bills", assembly.header, billColumns, billRows);

  const lineColumns = ["Bill ID", "Bill Number", "Line Item ID", "Description", "Quantity", "Unit", "Rate", "Amount", "BOQ Reference"];
  const lineRows = assembly.bills.flatMap((bill: any) => bill.lineItems.map((item: any) => [
    cellValue(bill.identity.billId), cellValue(bill.identity.billNumber), cellValue(item.id),
    cellValue(item.description), cellValue(item.quantity), cellValue(item.unit), cellValue(item.rate),
    cellValue(item.amount), cellValue(item.boqReference),
  ]));
  appendSheet(workbook, "Line Items", assembly.header, lineColumns, lineRows);

  const paymentColumns = [
    "Bill ID", "Bill Number", "Record Type", "Payment Date", "Amount", "Mode", "Account",
    "Paid By", "Recorded By", "Status Recorded At", "Reference",
  ];
  const paymentRows = assembly.bills.flatMap((bill: any) => bill.payments.map((payment: any) => [
    cellValue(bill.identity.billId), cellValue(bill.identity.billNumber), cellValue(payment.recordType),
    cellValue(payment.paymentDate), cellValue(payment.amount), cellValue(payment.mode), cellValue(payment.account),
    cellValue(payment.paidBy), cellValue(payment.recordedBy), cellValue(payment.statusRecordedAt),
    cellValue(payment.reference),
  ]));
  appendSheet(workbook, "Payments", assembly.header, paymentColumns, paymentRows);
  return workbook;
}
