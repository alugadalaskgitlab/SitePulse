export function getVolumeAtDepth(depthCm: number): number {
  if (depthCm <= 0) return 0;
  if (depthCm >= 250) return 52033;

  const lowerIndex = Math.floor(depthCm) - 1;
  const upperIndex = Math.ceil(depthCm) - 1;

  if (lowerIndex === upperIndex || Math.ceil(depthCm) === Math.floor(depthCm)) {
    return BITUMEN_DIP_CHART[lowerIndex].volume;
  }

  const lowerEntry = BITUMEN_DIP_CHART[lowerIndex];
  const upperEntry = BITUMEN_DIP_CHART[upperIndex];
  const fraction = depthCm - Math.floor(depthCm);

  return lowerEntry.volume + fraction * (upperEntry.volume - lowerEntry.volume);
}

export function getDeadStockVolume(deadStockDepthCm: number = DEFAULT_DEAD_STOCK_DEPTH): number {
  return getVolumeAtDepth(deadStockDepthCm);
}

export function getUsableVolume(depthCm: number, deadStockDepthCm: number = DEFAULT_DEAD_STOCK_DEPTH): number {
  const totalVolume = getVolumeAtDepth(depthCm);
  const deadStockVolume = getDeadStockVolume(deadStockDepthCm);
  return Math.max(0, totalVolume - deadStockVolume);
}
